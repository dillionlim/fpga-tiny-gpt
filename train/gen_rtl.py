"""Generate ROM images, parameters and the op program for rtl/llm_core.v.

  python3 -I gen_rtl.py params_C.pkl ../rtl/gen
Writes weights.hex, mults.hex, exp.hex, params.vh, program.vh and model.json.
"""
import json
import math
import os
import pickle
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from intref import EXP_LUT  # noqa: E402
from vocab import CHARS  # noqa: E402

OP_END, OP_EMBED, OP_NORM, OP_MATVEC, OP_ATTN, OP_SAMPLE = range(6)
M_ACT, M_RELU, M_KC, M_VC, M_RESID, M_LOGIT = range(6)
ACT_N, ACT_Q, ACT_A, ACT_H = 0, 64, 128, 256


def build(p):
    c = p["cfg"]
    d, L, V, ffn = c["d"], c["n_layer"], c["vocab"], c["ffn"]
    hd = d // c["n_head"]
    assert d == 64 and V == 64 and ffn <= 256 and c["ctx"] == 128 and hd == 16
    assert c["n_kv_head"] == 1, "RTL implements multi-query attention"

    wrom, mrom, prog = [], [], []
    wrom.append(p["emb"].reshape(-1))
    prog.append(dict(op=OP_EMBED, w=0, shift=8 - p["emb_shift"]))

    def matvec(w, m, shift, inp, mode, dst=0, layer=0):
        rows, cols = w.shape
        prog.append(dict(op=OP_MATVEC, w=sum(len(a) for a in wrom), m=sum(len(a) for a in mrom),
                         rows=rows, cols=cols, shift=shift, inp=inp, mode=mode, dst=dst, layer=layer))
        wrom.append(w.reshape(-1))
        mrom.append(np.asarray(m, dtype=np.int64))

    for l in range(L):
        P = p["layers"][l]
        prog.append(dict(op=OP_NORM, dst=ACT_N))
        matvec(P["wq"], P["mq"], P["sq"], ACT_N, M_ACT, ACT_Q)
        matvec(P["wk"], P["mk"], P["sk"], ACT_N, M_KC, layer=l)
        matvec(P["wv"], P["mv"], P["sv"], ACT_N, M_VC, layer=l)
        prog.append(dict(op=OP_ATTN, layer=l, inp=ACT_Q, dst=ACT_A, attm=p["att_m"][l], shift=p["att_s"][l]))
        matvec(P["wo"], P["mo"], P["so"], ACT_A, M_RESID)
        prog.append(dict(op=OP_NORM, dst=ACT_N))
        matvec(P["w1"], P["m1"], P["s1"], ACT_N, M_RELU, ACT_H)
        matvec(P["w2"], P["m2"], P["s2"], ACT_H, M_RESID)
    prog.append(dict(op=OP_NORM, dst=ACT_N))
    prog.append(dict(op=OP_MATVEC, w=0, m=0, rows=V, cols=d, shift=1, inp=ACT_N, mode=M_LOGIT, dst=0, layer=0))
    prog.append(dict(op=OP_SAMPLE))
    prog.append(dict(op=OP_END))

    wrom = np.concatenate(wrom).astype(np.int64)
    mrom = np.concatenate(mrom).astype(np.int64)
    return wrom, mrom, prog


def bound_checks(p):
    """Worst-case widths the RTL relies on."""
    for l in range(p["cfg"]["n_layer"]):
        zmax = (16 * 127 * 127 * p["att_m"][l]) >> p["att_s"][l]
        assert zmax < 2 ** 30, zmax
        for n in "qkvo12":
            assert p["layers"][l]["s" + n] <= 47


def main():
    with open(sys.argv[1], "rb") as f:
        p = pickle.load(f)
    out = sys.argv[2]
    os.makedirs(out, exist_ok=True)
    bound_checks(p)
    wrom, mrom, prog = build(p)
    c = p["cfg"]

    with open(f"{out}/weights.hex", "w") as f:
        f.write("\n".join(f"{int(b) & 0xFF:02x}" for b in wrom) + "\n")
    with open(f"{out}/mults.hex", "w") as f:
        f.write("\n".join(f"{int(m):04x}" for m in mrom) + "\n")
    with open(f"{out}/exp.hex", "w") as f:
        f.write("\n".join(f"{int(e):04x}" for e in EXP_LUT) + "\n")

    w_aw = max(1, math.ceil(math.log2(len(wrom))))
    m_aw = max(1, math.ceil(math.log2(len(mrom))))
    lb = max(1, math.ceil(math.log2(c["n_layer"])))
    with open(f"{out}/params.vh", "w") as f:
        f.write("// generated by gen_rtl.py\n")
        f.write(f"localparam NL = {c['n_layer']};\nlocalparam FFN = {c['ffn']};\n")
        f.write(f"localparam NORM_G = {c['norm_g']};\n")
        f.write(f"localparam W_DEPTH = {len(wrom)};\nlocalparam W_AW = {w_aw};\n")
        f.write(f"localparam M_DEPTH = {len(mrom)};\nlocalparam M_AW = {m_aw};\n")
        f.write(f"localparam LB = {lb};\nlocalparam KV_DEPTH = {c['n_layer'] * 4096};\n")
        f.write(f"localparam KV_AW = {lb + 12};\n")

    with open(f"{out}/program.vh", "w") as f:
        f.write("// generated by gen_rtl.py: one op per pc\n")
        f.write("task load_op(input [5:0] lpc);\n  begin\n")
        f.write("    op_code <= 0; op_mode <= 0; op_layer <= 0; op_in <= 0; op_cols <= 0; op_rows <= 0;\n")
        f.write("    op_w <= 0; op_m <= 0; op_shift <= 0; op_dst <= 0; op_attm <= 0;\n")
        f.write("    case (lpc)\n")
        for i, o in enumerate(prog):
            fields = [f"op_code <= {o['op']};"]
            for k, reg in [("mode", "op_mode"), ("layer", "op_layer"), ("inp", "op_in"), ("cols", "op_cols"),
                           ("rows", "op_rows"), ("w", "op_w"), ("m", "op_m"), ("shift", "op_shift"),
                           ("dst", "op_dst"), ("attm", "op_attm")]:
                if k in o:
                    fields.append(f"{reg} <= {o[k]};")
            f.write(f"      {i}: begin {' '.join(fields)} end\n")
        f.write("      default: op_code <= 0;\n    endcase\n  end\nendtask\n")

    meta = {"cfg": c, "logit_k": p["logit_k"], "chars": CHARS, "n_ops": len(prog),
            "w_bytes": len(wrom), "m_words": len(mrom)}
    with open(f"{out}/model.json", "w") as f:
        json.dump(meta, f, indent=1)
    print(f"weights {len(wrom)} B, mults {len(mrom)}, ops {len(prog)}, logit_k {p['logit_k']:.6g}")


if __name__ == "__main__":
    main()
